# Variables and Data Types

# Strings
username = "john"
email = "john@example.com"

# Integers
age = 25

# Float
price = 1500.50

# Boolean
is_active = True

print(username)
print(email)
print(age)
print(price)
print(is_active)

# Check data types
print(type(username))
print(type(age))
print(type(price))
print(type(is_active))

# Variables can change / reassign values
age = 26

print("Updated age:", age)