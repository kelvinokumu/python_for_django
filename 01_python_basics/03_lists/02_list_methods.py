# List methods
products = [
    "Laptop",
    "Phone",
    "Keyboard"
]
# Add
products.append("Mouse")

# Insert at a specific position
products.insert(1, "Monitor")
print(products)

# Remove
products.remove("Phone")
print(products)

# Sort
products.sort()
print(products)

# Reverse
products.reverse()
print(products)