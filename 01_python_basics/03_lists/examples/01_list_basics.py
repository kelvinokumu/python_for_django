# Lists
students = [
    "John",
    "Jane",
    "Peter",
    "Mary"
]
print(students)

# Access items
print(students[0]) # first item
print(students[-1]) # last item

# Number of items
print(len(students))

# Change an item
students[0] = "Kelvin"
print(students)

# Add an item
students.append("Brian")
print(students)